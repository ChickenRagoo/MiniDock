"""Удаление программ с компьютера прямо из Launchpad.

plan() решает, как удалить приложение, и возвращает описание для меню; run() выполняет его:
  registry — деинсталлятор из списка установленных программ (как в «Приложения и возможности»), в тихом режиме;
  store    — приложение Microsoft Store (Remove-AppxPackage);
  steam    — игра Steam (удаляет сам Steam, он спросит подтверждение в своём окне);
  portable — программа без установщика: её папка и ярлыки переносятся в корзину (можно восстановить);
  dead     — программы уже нет, остался ярлык: в корзину уходит только ярлык.
"""
import os
import re
import subprocess
import sys
import threading
import time
import winreg

import psutil
import win32con
import win32event
from win32com.propsys import propsys, pscon
from win32com.shell import shell, shellcon

UNINSTALL_KEY = r"SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall"
SYSROOT = os.environ.get("SystemRoot", r"C:\Windows").lower()
KNOWN_FOLDERS = {
    "{6D809377-6AF0-444B-8957-A3773F02200E}": os.environ.get("ProgramW6432", r"C:\Program Files"),
    "{7C5A40EF-A0FB-4BFC-874A-C0F2E0B9FA8E}": os.environ.get("ProgramFiles(x86)", r"C:\Program Files (x86)"),
    "{F38BF404-1D43-42F2-9305-67DE0B28FC23}": os.environ.get("SystemRoot", r"C:\Windows"),
    "{1AC14E77-02E7-4E5D-B744-2EB1AE5198B7}": os.path.join(os.environ.get("SystemRoot", r"C:\Windows"), "System32"),
}
# подпапки внутри папки программы, из которых запускается exe (поднимаемся до самой папки программы)
INNER_DIRS = re.compile(r"^(bin|bin64|bin32|x64|x86|64bit|32bit|win64|win32|binaries|app|application|release|"
                        r"app-[\d.]+|current)$", re.I)

_tls = threading.local()  # COM-объект ярлыков свой в каждом потоке (удаление идёт в фоне)


# -- что за программа -------------------------------------------------------------------------------------

def _shortcut(path):
    """(цель, аргументы) ярлыка .lnk."""
    try:
        if getattr(_tls, "wsh", None) is None:
            import pythoncom
            import win32com.client
            pythoncom.CoInitialize()
            _tls.wsh = win32com.client.Dispatch("WScript.Shell")
        sc = _tls.wsh.CreateShortCut(path)
        return sc.Targetpath or "", sc.Arguments or ""
    except Exception:
        return "", ""


def resolve(parse):
    """(exe, аргументы) для записи Launchpad: путь, ярлык или ID приложения из меню «Пуск»."""
    m = re.match(r"^(\{[0-9A-Fa-f-]+\})\\(.+)$", parse)
    if m and m.group(1).upper() in KNOWN_FOLDERS:
        parse = os.path.join(KNOWN_FOLDERS[m.group(1).upper()], m.group(2))
    low = parse.lower()
    if low.endswith(".lnk") and os.path.isfile(parse):
        return _shortcut(parse)
    if low.endswith(".exe"):
        return parse, ""
    if "\\" in parse or "://" in parse:
        return "", ""
    try:  # ID приложения (Telegram.TelegramDesktop, 308046B0AF4A39CB, Microsoft.AutoGenerated.{…})
        item = shell.SHCreateItemFromParsingName("shell:AppsFolder\\" + parse, None, shell.IID_IShellItem2)
        target = item.GetString(pscon.PKEY_Link_TargetParsingPath)
        try:
            args = item.GetString(propsys.PSGetPropertyKeyFromName("System.Link.Arguments"))
        except Exception:
            args = ""
        return target or "", args or ""
    except Exception:
        return "", ""


def store_family(parse):
    """Имя пакета приложения Microsoft Store (parse = «Семейство_издатель!Приложение»)."""
    if "!" in parse and "\\" not in parse and "://" not in parse:
        return parse.split("!", 1)[0]
    return None


# без этих пакетов ломаются магазин, установка приложений, защита и сама Windows
KEEP_PACKAGES = ("microsoft.windowsstore", "microsoft.storepurchaseapp", "microsoft.desktopappinstaller",
                 "microsoft.sechealthui", "microsoft.windows.", "microsoft.windowsdefender", "microsoft.ui.xaml",
                 "microsoft.vclibs", "microsoft.net", "microsoft.services.store")

_system_packages = None


def system_packages():
    """Пакеты Store, которые Windows не даёт удалить (Защитник, Параметры и т.п.) или которые входят в систему."""
    global _system_packages
    if _system_packages is None:
        try:
            out = subprocess.run(["powershell", "-NoProfile", "-NonInteractive", "-Command",
                                  "Get-AppxPackage | Where-Object { $_.NonRemovable -or $_.SignatureKind -eq 'System' }"
                                  " | ForEach-Object { $_.PackageFamilyName }"],
                                 capture_output=True, text=True, timeout=30,
                                 creationflags=subprocess.CREATE_NO_WINDOW).stdout
            _system_packages = {x.strip().casefold() for x in out.splitlines() if x.strip()}
        except Exception:
            _system_packages = set()
    return _system_packages


def preload():
    """Заранее (в фоне) прочитать список программ и системных пакетов — меню потом открывается сразу."""
    threading.Thread(target=lambda: (entries(), system_packages()), daemon=True).start()


# -- список установленных программ ------------------------------------------------------------------------

def _entries():
    out = []
    for root, view in ((winreg.HKEY_LOCAL_MACHINE, winreg.KEY_WOW64_64KEY),
                       (winreg.HKEY_LOCAL_MACHINE, winreg.KEY_WOW64_32KEY),
                       (winreg.HKEY_CURRENT_USER, 0)):
        try:
            k = winreg.OpenKey(root, UNINSTALL_KEY, 0, winreg.KEY_READ | view)
        except OSError:
            continue
        for i in range(winreg.QueryInfoKey(k)[0]):
            key = winreg.EnumKey(k, i)
            try:
                s = winreg.OpenKey(k, key)
            except OSError:
                continue

            def v(name):
                try:
                    return winreg.QueryValueEx(s, name)[0]
                except OSError:
                    return ""
            name, cmd = v("DisplayName"), v("UninstallString")
            if not name or not cmd or v("SystemComponent") == 1:
                continue
            out.append(dict(name=str(name), location=str(v("InstallLocation") or ""), icon=str(v("DisplayIcon") or ""),
                            uninstall=str(cmd), quiet=str(v("QuietUninstallString") or ""), key=key,
                            msi=v("WindowsInstaller") == 1, machine=root == winreg.HKEY_LOCAL_MACHINE))
    return out


_cache = (0.0, [])


def entries():
    """Список установленных программ (кэш на 20 с — меню открывается быстро)."""
    global _cache
    if time.monotonic() - _cache[0] > 20:
        _cache = (time.monotonic(), _entries())
    return _cache[1]


def _clean_path(p):
    p = p.strip().strip('"')
    p = re.sub(r",\s*-?\d+$", "", p).strip('"')
    return os.path.normpath(os.path.expandvars(p)).lower() if p else ""


def _exe_of(cmd):
    cmd = cmd.strip()
    if cmd.startswith('"'):
        end = cmd.find('"', 1)
        return cmd[1:end], cmd[end + 1:].strip()
    m = re.match(r"(.+?\.exe)\b(.*)$", cmd, re.I)
    if m:
        return m.group(1), m.group(2).strip()
    parts = cmd.split(" ", 1)
    return parts[0], parts[1] if len(parts) > 1 else ""


def _generic(folder):
    """Слишком общая папка (Program Files, профиль, «Загрузки», корень диска…) — её не трогаем и по ней не опознаём."""
    f = os.path.normpath(folder).rstrip("\\").lower() if folder else ""
    if not f or len(f) <= 3:
        return True
    home = os.environ.get("USERPROFILE", "")
    generic = {os.path.normpath(os.environ.get(v, "") or "x").lower() for v in
               ("ProgramFiles", "ProgramFiles(x86)", "ProgramW6432", "LOCALAPPDATA", "APPDATA", "USERPROFILE",
                "SystemRoot", "ProgramData", "PUBLIC", "TEMP", "CommonProgramFiles", "CommonProgramFiles(x86)")}
    for sub in ("Desktop", "Downloads", "Documents", "Favorites", r"Favorites\Downloads", r"Favorites\Downloads\Documents",
                r"AppData\Local\Programs", "Saved Games", "OneDrive", "Pictures", "Videos", "Music"):
        generic.add(os.path.normpath(os.path.join(home, sub)).lower())
    return f in generic or f.startswith(SYSROOT) or "\\windowsapps" in f


def _norm_name(n):
    """Название без версий и разрядности: «Python 3.12 (64-bit)» → «python»."""
    n = re.sub(r"\(.*?\)|\b(x64|x86|64-?bit|32-?bit|v?\d[\d.]*)\b", " ", n.casefold())
    return " ".join(re.findall(r"[^\W_]+", n))


def find(exe, name):
    """Запись программы для exe и названия, или None (при сомнениях — None: лучше не удалить, чем удалить чужое)."""
    exe = os.path.normpath(exe).lower() if exe else ""
    best, best_score = None, 0
    norm = _norm_name(name or "")
    norm_hits = []
    for e in entries():
        score = 0
        icon = _clean_path(e["icon"])
        loc = _clean_path(e["location"]) if e["location"] else ""
        unin_dir = os.path.dirname(_clean_path(_exe_of(e["uninstall"])[0]))
        if "://" in e["uninstall"]:  # удаление через лаунчер (steam://uninstall/…) — это игра, а не сам лаунчер
            unin_dir = ""
        if exe:
            if icon and icon == exe:
                score = 100
            elif loc and not _generic(loc) and exe.startswith(loc.rstrip("\\") + "\\"):
                score = 80 + len(loc) / 1000
            elif unin_dir and not _generic(unin_dir) and exe.startswith(unin_dir + "\\"):
                score = 60 + len(unin_dir) / 1000
        dn = e["name"].casefold()
        n = (name or "").casefold()
        if n and dn == n:
            score = max(score, 50) + 15  # точное совпадение названия важнее совпадения папки
        elif n and len(n) >= 4 and (dn.startswith(n) or n.startswith(dn)):
            score = max(score, 30) + 5
        if norm and _norm_name(e["name"]) == norm:
            norm_hits.append(e)
        if score > best_score:
            best, best_score = e, score
    if best_score < 30 and len(norm_hits) == 1:  # «Python 3.12 (64-bit)» ↔ «Python 3.12.4 (64-bit)», только без двусмысленности
        return norm_hits[0]
    return best if best_score >= 30 else None


def local_uninstaller(exe):
    """Деинсталлятор в папке программы или на 1–2 уровня выше (как у OBS: bin\\64bit\\obs64.exe → uninstall.exe)."""
    if not exe:
        return None
    folder = os.path.dirname(exe)
    for _ in range(3):
        if _generic(folder):
            return None
        try:
            names = os.listdir(folder)
        except OSError:
            return None
        for f in names:
            fl = f.lower()
            if fl.endswith(".exe") and (re.fullmatch(r"unins\d{3}\.exe", fl) or fl in ("uninstall.exe", "uninst.exe")
                                        or fl.startswith("uninstall ")):
                p = os.path.join(folder, f)
                home = os.environ.get("USERPROFILE", "").lower()
                return dict(name=os.path.basename(folder), location=folder, icon="", uninstall=f'"{p}"', quiet="",
                            key="", msi=False, machine=not folder.lower().startswith(home))
        folder = os.path.dirname(folder)
    return None


def _is_nsis(path):
    try:
        with open(path, "rb") as f:
            return b"Nullsoft" in f.read(4 * 1024 * 1024)
    except OSError:
        return False


def silent_command(e):
    """Команда тихого удаления: (exe, параметры)."""
    if e["quiet"]:
        return _exe_of(e["quiet"])
    cmd = e["uninstall"]
    guid = re.search(r"\{[0-9A-Fa-f-]{36}\}", cmd)
    if e["msi"] or re.match(r'"?msiexec', cmd, re.I):
        code = guid.group(0) if guid else e["key"]
        return "msiexec.exe", f"/x {code} /qn /norestart"
    exe, args = _exe_of(cmd)
    base = os.path.basename(exe).lower()
    low = args.lower()
    if re.fullmatch(r"unins\d{3}\.exe", base):  # Inno Setup
        args += " /VERYSILENT /SUPPRESSMSGBOXES /NORESTART"
    elif base == "update.exe" and "--uninstall" in low:  # Squirrel (Discord, Slack…)
        args += " -s"
    elif base == "setup.exe" and "--uninstall" in low:  # Chromium (Chrome, Edge…)
        args += " --force-uninstall"
    elif "/uninstall" in low and "silent" not in low:  # Spotify и похожие
        args += " /silent"
    elif _is_nsis(exe):
        args += " /S"
    return exe, args.strip()


# -- портативные программы -------------------------------------------------------------------------------

def _tokens(s):
    return {t for t in re.findall(r"[^\W_]+", s.casefold()) if len(t) >= 2 and not t.isdigit()}


def app_folder(exe):
    """Папка портативной программы: от exe поднимаемся из служебных подпапок (bin, x64, app-1.2…)."""
    folder = os.path.dirname(exe)
    while INNER_DIRS.match(os.path.basename(folder)) and not _generic(os.path.dirname(folder)):
        folder = os.path.dirname(folder)
    return folder


def _self_inside(folder):
    """MiniDock сам лежит в этой папке (или запущен из неё) — такую папку не удаляем."""
    f = os.path.normpath(folder).lower() + "\\"
    mine = [sys.executable, os.path.abspath(sys.argv[0]) if sys.argv and sys.argv[0] else "", __file__]
    return any(os.path.normpath(p).lower().startswith(f) for p in mine if p)


def _company(exe):
    try:
        import win32api
        lang, cp = win32api.GetFileVersionInfo(exe, "\\VarFileInfo\\Translation")[0]
        return win32api.GetFileVersionInfo(exe, f"\\StringFileInfo\\{lang:04x}{cp:04x}\\CompanyName") or ""
    except Exception:
        return ""


def _is_project(folder):
    """Папка с исходниками (git, проект Node/Python/.NET) — не «программа», в корзину не отправляем."""
    try:
        names = {n.lower() for n in os.listdir(folder)}
    except OSError:
        return True
    return bool(names & {".git", "package.json", "pyproject.toml", "setup.py", "cargo.toml", ".vs"}) \
        or any(n.endswith((".sln", ".csproj")) for n in names)


def portable_folder(exe, args, name):
    """Папка, которую можно отправить в корзину, или None, если это небезопасно."""
    if not exe or args.strip() or not os.path.isfile(exe):
        return None  # ярлык с аргументами — это запуск через лаунчер, папка не принадлежит этому приложению
    folder = app_folder(exe)
    if _generic(folder) or _self_inside(folder) or "microsoft office" in folder.lower() or _is_project(folder):
        return None
    if "microsoft" in _company(exe).lower():  # Internet Explorer, Media Player, OneDrive — части Windows
        return None
    # название приложения должно совпадать с названием папки: «Slime Rancher 2» → E:\Hydra — чужая папка
    if not (_tokens(name) & _tokens(os.path.basename(folder))):
        return None
    return folder


def _start_menu_dirs():
    out = []
    for csidl in (shellcon.CSIDL_PROGRAMS, shellcon.CSIDL_COMMON_PROGRAMS, shellcon.CSIDL_DESKTOPDIRECTORY,
                  shellcon.CSIDL_COMMON_DESKTOPDIRECTORY):
        try:
            out.append(shell.SHGetFolderPath(0, csidl, None, 0))
        except Exception:
            pass
    return out


def shortcuts_to(target=None, folder=None):
    """Ярлыки в меню «Пуск» и на рабочих столах, ведущие на target (или куда-то внутрь folder)."""
    t = os.path.normpath(target).lower() if target else None
    f = os.path.normpath(folder).lower() + "\\" if folder else None
    found = []
    for d in _start_menu_dirs():
        for root, _, files in os.walk(d):
            for name in files:
                if not name.lower().endswith(".lnk"):
                    continue
                p = os.path.join(root, name)
                raw = _shortcut(p)[0]
                tgt = os.path.normpath(raw).lower() if raw else ""
                if tgt and ((t and tgt == t) or (f and tgt.startswith(f))):
                    found.append(p)
    return found


def recycle(paths):
    """В корзину, без вопросов. Если что-то в корзину не помещается, Windows спросит, а не удалит молча."""
    if not paths:
        return
    flags = shellcon.FOF_ALLOWUNDO | shellcon.FOF_NOCONFIRMATION | shellcon.FOF_WANTNUKEWARNING | shellcon.FOF_SILENT
    shell.SHFileOperation((0, shellcon.FO_DELETE, "\0".join(paths), None, flags, None, None))


# -- план и выполнение --------------------------------------------------------------------------------------

def plan(parse, name):
    """Как удалить приложение: dict(kind, label, …) или None, если удалить нельзя."""
    q = f"«{name}»"
    fam = store_family(parse)
    if fam:
        if fam.casefold() in system_packages() or fam.casefold().startswith(KEEP_PACKAGES):
            return None
        return dict(kind="store", family=fam, label=f"Удалить {q} навсегда")
    m = re.match(r"steam://(?:rungameid|run)/(\d+)", parse, re.I)
    if m:
        return dict(kind="steam", appid=m.group(1), label=f"Удалить {q} через Steam")
    exe, args = resolve(parse)
    exe = os.path.expandvars(exe)
    if not exe or not re.match(r"^[a-zA-Z]:\\", exe):
        return None  # «Этот компьютер», «Выполнить» и прочие системные объекты — не файлы
    low = os.path.normpath(exe).lower()
    if low.startswith(SYSROOT) or "\\windowsapps\\" in low or "microsoft office" in low:
        return None  # части Windows и Office по отдельности не удаляются
    if not os.path.isfile(exe):
        if not os.path.isdir(exe[:3]):
            return None  # диск не подключён — программа может быть на месте
        return dict(kind="dead", exe=exe, label=f"Убрать ярлык {q} (программы уже нет)")
    e = find(low, name) or local_uninstaller(low)
    if e is not None:
        label = f"Удалить {q} навсегда"
        if _norm_name(e["name"]) != _norm_name(name) and not _tokens(name) <= _tokens(e["name"]):
            if args.strip():
                return None  # ярлык с аргументами ведёт в чужую программу (веб-приложение Firefox, игра через лаунчер)
            label += f"  (удалится всё: {e['name']})"  # «Benchmark» — это часть Equalizer APO
        return dict(kind="registry", entry=e, label=label)
    folder = portable_folder(exe, args, name)
    if folder:
        return dict(kind="portable", folder=folder, exe=exe, label=f"Переместить {q} в корзину  ({folder})")
    return None


def run(p, on_done):
    """Выполнить план; on_done() — из фонового потока, когда закончили. False — запустить не удалось."""
    kind = p["kind"]
    if kind == "store":
        ps = f"Get-AppxPackage -PackageFamilyName '{p['family']}' | Remove-AppxPackage"
        proc = subprocess.Popen(["powershell", "-NoProfile", "-NonInteractive", "-Command", ps],
                                creationflags=subprocess.CREATE_NO_WINDOW)
        threading.Thread(target=lambda: (proc.wait(), on_done()), daemon=True).start()
        return True
    if kind == "steam":
        os.startfile(f"steam://uninstall/{p['appid']}")
        threading.Thread(target=lambda: (time.sleep(15), on_done()), daemon=True).start()
        return True
    if kind == "dead":
        threading.Thread(target=lambda: (recycle(shortcuts_to(target=p["exe"])), on_done()), daemon=True).start()
        return True
    if kind == "portable":
        def work():
            folder = os.path.normpath(p["folder"]).lower() + "\\"
            for proc in psutil.process_iter(["exe"]):  # запущенная программа не даст удалить свои файлы
                try:
                    if proc.info["exe"] and os.path.normpath(proc.info["exe"]).lower().startswith(folder):
                        proc.terminate()
                except psutil.Error:
                    pass
            time.sleep(1.5)
            recycle([p["folder"]] + shortcuts_to(folder=p["folder"]))
            on_done()
        threading.Thread(target=work, daemon=True).start()
        return True
    e = p["entry"]
    file, params = silent_command(e)
    try:
        # программы «для всех пользователей» удаляются только с правами администратора — Windows спросит один раз
        info = shell.ShellExecuteEx(fMask=shellcon.SEE_MASK_NOCLOSEPROCESS | shellcon.SEE_MASK_FLAG_NO_UI,
                                    lpVerb="runas" if e["machine"] else "open", lpFile=file,
                                    lpParameters=params, nShow=win32con.SW_HIDE)
    except Exception:
        return False
    handle = info.get("hProcess")

    def wait():
        if handle:
            win32event.WaitForSingleObject(handle, win32event.INFINITE)
        on_done()
    threading.Thread(target=wait, daemon=True).start()
    return True
